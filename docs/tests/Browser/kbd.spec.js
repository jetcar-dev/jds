import {expect, test} from '@playwright/test'

test('Keyboard Key matches HeroUI v2 structure and appearance', async ({page}) => {
    await page.goto('/components/kbd')

    const basic = page.locator('[data-preview-name="kbd-basic"] [data-ui-component="kbd"]')
    await expect(basic).toHaveCSS('display', 'flex')
    await expect(basic).toHaveCSS('height', '24px')
    await expect(basic).toHaveCSS('padding', '2px 6px')
    await expect(basic).toHaveCSS('gap', '2px')
    await expect(basic).toHaveCSS('font-size', '14px')
    await expect(basic).toHaveCSS('line-height', '20px')
    await expect(basic).toHaveCSS('font-weight', '400')
    await expect(basic).toHaveCSS('border-width', '0px')
    await expect(basic).toHaveCSS('border-radius', '8px')
    await expect(basic).not.toHaveCSS('box-shadow', 'none')
    await expect(basic.locator('[data-slot="abbr"]')).toHaveAttribute('title', 'Command')
    await expect(basic.locator('[data-slot="content"]')).toHaveText('K')

    const combinations = page.locator('[data-preview-name="kbd-combinations"] [data-ui-component="kbd"]')
    await expect(combinations).toHaveCount(3)
    await expect(combinations.nth(1).locator('[data-slot="abbr"]')).toHaveCount(2)
    await expect(combinations.nth(1).locator('[data-slot="abbr"]').nth(0)).toHaveText('⌘')
    await expect(combinations.nth(1).locator('[data-slot="abbr"]').nth(1)).toHaveText('⇧')
    await expect(combinations.nth(1).locator('[data-slot="content"]')).toHaveText('N')

    const platforms = page.locator('[data-preview-name="kbd-platforms"] [data-ui-component="kbd"]')
    await expect(platforms).toHaveCount(5)
    await expect(platforms.nth(2)).toHaveAttribute('data-platform', 'windows')
    await expect(platforms.nth(2).locator('[data-slot="abbr"]')).toHaveText('Win')
    await expect(platforms.nth(2).locator('[data-slot="content"]')).toHaveText('D')
    await expect(platforms.nth(2).locator('[data-slot="separator"]')).toHaveCount(1)
    await expect(platforms.nth(2).locator('[data-slot="separator"] .app-icon')).toHaveAttribute('data-icon', 'material-symbols:add-rounded')
    await expect(platforms.nth(2).locator('[data-slot="separator"] .app-icon')).toHaveCSS('width', '12px')
    await expect(platforms.nth(2).locator('[data-slot="separator"] .app-icon')).toHaveCSS('height', '12px')
    await expect(platforms.nth(3).locator('[data-slot="abbr"]')).toHaveCount(3)
    await expect(platforms.nth(3).locator('[data-slot="abbr"]').nth(0)).toHaveText('Ctrl')
    await expect(platforms.nth(3).locator('[data-slot="abbr"]').nth(1)).toHaveText('Shift')
    await expect(platforms.nth(3).locator('[data-slot="abbr"]').nth(2)).toHaveText('Esc')
    await expect(platforms.nth(3).locator('[data-slot="separator"]')).toHaveCount(2)
    await expect(platforms.nth(4).locator('[data-slot="abbr"]')).toHaveCount(2)
    await expect(platforms.nth(4).locator('[data-slot="abbr"]').nth(0)).toHaveText('Alt')
    await expect(platforms.nth(4).locator('[data-slot="abbr"]').nth(1)).toHaveText('Tab')
    await expect(platforms.nth(4).locator('[data-slot="separator"]')).toHaveCount(1)

    const allKeys = page.locator('[data-preview-name="kbd-keys"] [data-ui-component="kbd"]')
    await expect(allKeys).toHaveCount(22)
})

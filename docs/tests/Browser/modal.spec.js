import {expect, test} from '@playwright/test'

test('Modal matches HeroUI geometry, focus trap and focus restoration', async ({page}) => {
    await page.goto('/components/modal')

    const preview = page.locator('[data-preview-name="modal-basic"]')
    const trigger = preview.getByRole('button', {name: 'Modal 열기'})
    await trigger.click()

    const dialog = page.getByRole('dialog', {name: '회원 추가'})
    await expect(dialog).toBeVisible()
    await expect(dialog).toHaveCSS('max-width', '448px')
    await expect(dialog).toHaveCSS('border-radius', '14px')
    await expect(dialog).toHaveCSS('box-shadow', /0px 2px 10px/)
    const closeButton = dialog.getByRole('button', {name: '닫기'})
    await expect(closeButton).toBeFocused()
    await expect(closeButton).not.toHaveAttribute('data-focus-visible', 'true')
    await expect(dialog).toHaveAttribute('aria-describedby', /description/)

    await dialog.getByRole('button', {name: '닫기'}).click()
    await expect(dialog).toBeHidden()
    await expect(trigger).toBeFocused()

    await trigger.press('Enter')
    await expect(closeButton).toHaveAttribute('data-focus-visible', 'true')
    await closeButton.click()
})

test('Modal supports dismiss rules, external triggers and scrolling', async ({page}) => {
    await page.goto('/components/modal')

    const lockedPreview = page.locator('[data-preview-name="modal-non-dismissible"]')
    const lockedTrigger = lockedPreview.getByRole('button', {name: '닫기 제한 Modal'})
    await lockedTrigger.click()
    const lockedDialog = page.getByRole('dialog', {name: '작업을 완료해 주세요'})
    await expect(lockedDialog).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(lockedDialog).toBeVisible()
    await page.locator('[data-overlay-layer]:visible [data-overlay-wrapper]').click({position: {x: 2, y: 2}})
    await expect(lockedDialog).toBeVisible()
    await lockedDialog.getByRole('button', {name: '완료'}).click()
    await expect(lockedDialog).toBeHidden()

    const sharedPreview = page.locator('[data-preview-name="modal-external-triggers"]')
    const externalTrigger = sharedPreview.getByRole('button', {name: '담당자 선택'})
    await externalTrigger.click()
    const sharedDialog = page.getByRole('dialog', {name: '회원 선택'})
    await expect(sharedDialog).toBeVisible()
    await sharedDialog.getByRole('button', {name: '닫기'}).last().click()
    await expect(externalTrigger).toBeFocused()

    const scrollPreview = page.locator('[data-preview-name="modal-scroll"]')
    await scrollPreview.getByRole('button', {name: 'inside'}).click()
    const insideDialog = page.getByRole('dialog', {name: 'inside 스크롤'})
    await expect(insideDialog.locator('[data-slot="modal-body"]')).toHaveCSS('overflow-y', 'auto')
})

test('Modal portals before painting and supports custom backdrop, motion and dragging', async ({page}) => {
    await page.emulateMedia({reducedMotion: 'no-preference'})
    await page.goto('/components/modal')

    const basic = page.locator('[data-preview-name="modal-basic"]')
    await basic.getByRole('button', {name: 'Modal 열기'}).click()
    const basicDialog = page.getByRole('dialog', {name: '회원 추가'})
    expect(await basicDialog.evaluate(element => element.closest('[data-overlay-layer]')?.parentElement === document.body)).toBe(true)
    await expect(basicDialog).toHaveAttribute('data-open', 'true')
    await basicDialog.getByRole('button', {name: '닫기'}).click()

    const backdropPreview = page.locator('[data-preview-name="modal-custom-backdrop"]')
    await backdropPreview.getByRole('button', {name: '사용자 정의 배경'}).click()
    const backdropDialog = page.getByRole('dialog', {name: '사용자 정의 배경'})
    await expect(page.locator('[data-overlay-layer]:visible [data-slot="backdrop"] > div')).toHaveCSS('background-image', /radial-gradient/)
    await backdropDialog.getByRole('button', {name: '닫기'}).first().click()

    const motionPreview = page.locator('[data-preview-name="modal-custom-motion"]')
    await motionPreview.getByRole('button', {name: '사용자 정의 움직임'}).click()
    const motionDialog = page.getByRole('dialog', {name: '사용자 정의 움직임'})
    await expect.poll(() => motionDialog.locator('..').evaluate(element => element.getAnimations().length)).toBeGreaterThan(0)
    await motionDialog.getByRole('button', {name: '닫기'}).first().click()

    const dragPreview = page.locator('[data-preview-name="modal-draggable"]')
    await dragPreview.getByRole('button', {name: '화면 안에서 드래그'}).click()
    const dragDialog = page.getByRole('dialog', {name: 'Header를 드래그하세요'})
    const header = dragDialog.locator('[data-slot="modal-header"]')
    const before = await dragDialog.boundingBox()
    const handle = await header.boundingBox()
    await page.mouse.move(handle.x + 40, handle.y + 20)
    await page.mouse.down()
    await page.mouse.move(handle.x + 100, handle.y + 70, {steps: 4})
    await page.mouse.up()
    const after = await dragDialog.boundingBox()
    expect(after.x).toBeGreaterThan(before.x)
    expect(after.y).toBeGreaterThan(before.y)
})

test('Modal follows HeroUI responsive margins and motion', async ({page}) => {
    await page.emulateMedia({reducedMotion: 'no-preference'})
    await page.setViewportSize({width: 455, height: 800})
    await page.goto('/components/modal')

    const preview = page.locator('[data-preview-name="modal-basic"]')
    await preview.getByRole('button', {name: 'Modal 열기'}).click()
    const dialog = page.getByRole('dialog', {name: '회원 추가'})
    const mobileWrapperScroll = await dialog.locator('..').evaluate(element => ({clientHeight: element.clientHeight, scrollHeight: element.scrollHeight}))
    const mobileFrames = await dialog.locator('..').evaluate(element => element.getAnimations()[0]?.effect?.getKeyframes())
    await dialog.locator('..').evaluate(element => Promise.all(element.getAnimations().map(animation => animation.finished)))
    const mobileBox = await dialog.boundingBox()
    expect(mobileBox.x).toBeCloseTo(4, 0)
    expect(mobileBox.width).toBeCloseTo(447, 0)
    expect(mobileBox.y + mobileBox.height).toBeCloseTo(796, 0)
    expect(mobileWrapperScroll.scrollHeight).toBe(mobileWrapperScroll.clientHeight)
    expect(mobileFrames[0].transform).toContain('80px')
    await dialog.getByRole('button', {name: '닫기'}).click()

    await page.setViewportSize({width: 1280, height: 900})
    await preview.getByRole('button', {name: 'Modal 열기'}).click()
    const desktopFrames = await dialog.locator('..').evaluate(element => element.getAnimations()[0]?.effect?.getKeyframes())
    await dialog.locator('..').evaluate(element => Promise.all(element.getAnimations().map(animation => animation.finished)))
    const desktopBox = await dialog.boundingBox()
    expect(desktopBox.width).toBeCloseTo(448, 0)
    expect(desktopBox.x).toBeCloseTo(416, 0)
    expect(desktopFrames[0].transform).toContain('1.03')
})

test('Modal scroll lock does not shift the document', async ({page}) => {
    await page.goto('/components/modal')
    const title = page.getByRole('heading', {name: 'Modal', exact: true})
    const preview = page.locator('[data-preview-name="modal-basic"]')
    await page.evaluate(() => scrollTo(0, 200))
    const before = await title.boundingBox()
    const beforeBodyWidth = await page.locator('body').evaluate(element => element.getBoundingClientRect().width)
    const beforeScroll = await page.evaluate(() => scrollY)

    await preview.getByRole('button', {name: 'Modal 열기'}).click()
    const dialog = page.getByRole('dialog', {name: '회원 추가'})
    const after = await title.boundingBox()
    const afterBodyWidth = await page.locator('body').evaluate(element => element.getBoundingClientRect().width)

    expect(after.x).toBeCloseTo(before.x, 0)
    expect(afterBodyWidth).toBeCloseTo(beforeBodyWidth, 0)
    await expect(page.locator('html')).toHaveCSS('scrollbar-gutter', 'stable')
    await expect(page.locator('html')).toHaveCSS('overflow', 'hidden')
    await expect(page.locator('body')).toHaveCSS('position', 'static')
    await page.mouse.wheel(0, 500)
    expect(await page.evaluate(() => scrollY)).toBe(beforeScroll)

    await dialog.getByRole('button', {name: '닫기'}).click()
    await expect(page.locator('body')).toHaveCSS('position', 'static')
    await expect(page.locator('html')).toHaveCSS('scrollbar-gutter', 'auto')
    await expect(page.locator('html')).toHaveCSS('overflow-x', 'hidden')
    await expect(page.locator('html')).toHaveCSS('overflow-y', 'auto')
    expect(await page.evaluate(() => scrollY)).toBe(beforeScroll)
})
